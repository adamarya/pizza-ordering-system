import { z } from 'zod';
import { quoteRequestSchema } from '../cart/quote.schema.js';

// Request contract for POST /api/orders (Table 25, S2-14). The cart lines are the same shape the
// cart already sends to /api/cart/quote, so the server prices the order from the catalog exactly as
// it priced the quote. confirmedTotalCents is the total the customer saw on the review screen; if a
// fresh quote disagrees, the order is refused with 409 and the new quote (Figure 7).
//
// The contact, requested time, and delivery address rules here are the minimum order placement
// needs. The full checkout rules (store hours, delivery area, field messages) are S2-07 to S2-09,
// and this schema adopts that shared checkout schema once it is merged.
export const contactSchema = z
  .object({
    name: z.string().trim().min(1, 'Please enter your name.').max(80),
    phone: z
      .string()
      .trim()
      .regex(/^[0-9+().\-\s]{7,20}$/, 'Please enter a phone number we can call.'),
    email: z.string().trim().max(254).email('Please enter a valid email address.'),
  })
  .strict();

export const placeOrderSchema = quoteRequestSchema
  .extend({
    confirmedTotalCents: z.number().int().min(0).max(10_000_000),
    contact: contactSchema,
    requestedTime: z.string().datetime({ offset: true }).optional(),
    deliveryAddress: z.string().trim().min(5).max(200).optional(),
  })
  .superRefine((value, ctx) => {
    if (value.lines.length === 0) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['lines'], message: 'The cart is empty.' });
    }
    if (value.fulfillment === 'DELIVERY' && !value.deliveryAddress) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['deliveryAddress'], message: 'Please enter a delivery address.' });
    }
    if (value.fulfillment === 'PICKUP' && value.deliveryAddress) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['deliveryAddress'], message: 'Pickup orders do not take an address.' });
    }
  });

export type PlaceOrderRequest = z.infer<typeof placeOrderSchema>;

// One key per checkout, generated by the browser when the review screen opens (Figure 7).
export const idempotencyKeySchema = z.string().regex(/^[A-Za-z0-9_-]{16,100}$/);
