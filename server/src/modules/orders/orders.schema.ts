import { z } from 'zod';
import type { QuoteRequest } from '../cart/quote.schema.js';
import { checkoutFieldsSchema, refineCheckout, type DeliveryAddress } from '../checkout/checkout.schema.js';

// Request contract for POST /api/orders (Table 25, S2-14). The body is the same checkout request the
// review screen sent to POST /api/checkout/validate (S2-07 to S2-10), plus confirmedTotalCents, the
// total the customer saw on the review screen. The server reprices the order from the catalog; if
// the fresh quote disagrees, the order is refused with 409 and the new quote (Figure 7). The store
// hours, lead time, and delivery area rules are checked again here (checkout.rules.ts).
export const placeOrderSchema = checkoutFieldsSchema
  .extend({
    confirmedTotalCents: z.number().int().min(0).max(10_000_000),
  })
  .superRefine(refineCheckout);

export type PlaceOrderRequest = z.infer<typeof placeOrderSchema>;

// What the order service stores: the Order table keeps one customer name and one address line.
export interface OrderInput extends QuoteRequest {
  confirmedTotalCents: number;
  contact: { name: string; phone: string; email: string };
  requestedTime?: string;
  deliveryAddress?: string;
}

export function formatAddress(a: DeliveryAddress): string {
  const street = a.unitOrApt ? `${a.street}, ${a.unitOrApt}` : a.street;
  return `${street}, ${a.city}, ${a.state.toUpperCase()} ${a.zipCode}`;
}

export function toOrderInput(req: PlaceOrderRequest): OrderInput {
  const { customer, deliveryAddress, ...rest } = req;
  return {
    ...rest,
    contact: { name: `${customer.firstName} ${customer.lastName}`, phone: customer.phone, email: customer.email },
    deliveryAddress: req.fulfillment === 'DELIVERY' && deliveryAddress ? formatAddress(deliveryAddress) : undefined,
  };
}

// One key per checkout, generated by the browser when the review screen opens (Figure 7).
export const idempotencyKeySchema = z.string().regex(/^[A-Za-z0-9_-]{16,100}$/);
